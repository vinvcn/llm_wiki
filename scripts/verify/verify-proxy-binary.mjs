// Node contract gate for the binary-safe /api/proxy envelope (durable; /tmp
// is volatile).
//
// The desktop's Tauri HTTP plugin hands raw bytes to reqwest, so binary
// request bodies (MinerU cloud PDF PUT, local MinerU multipart FormData) must
// cross the web shim + /api/proxy BYTE-EXACT. This harness pins the server
// half of that contract against a mock upstream:
//
//   1. bodyBase64      → upstream receives the exact bytes (method/headers kept)
//   2. formEntries     → upstream receives a real multipart/form-data body:
//                         text fields + a byte-exact file part with filename
//                         and content type (boundary generated by the server)
//   3. binary response → upstream bytes stream back byte-exact (zip-ish blob
//                         full of non-UTF-8 bytes)
//   4. body (string)   → the pre-existing text/JSON contract is unchanged
//   5. bodyContentType → applied only when the caller sent no Content-Type
//   6. error semantics → 400 Invalid JSON / Missing url / Invalid url /
//                         Only http(s) URLs may be proxied / Ambiguous body
//
// Re-run against the Docker entry point with
// SERVER_ENTRY=packages/server/src/index-v2.js (same handleProxy, same
// contract; mounted before express.json() so the raw stream survives).
//
//   node scripts/verify/verify-proxy-binary.mjs

import { spawn } from "node:child_process"
import { fileURLToPath } from "node:url"
import fs from "node:fs"
import path from "node:path"
import os from "node:os"
import http from "node:http"
import crypto from "node:crypto"

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..")
const SERVER_ENTRY = process.env.SERVER_ENTRY || "packages/server/src/index.js"

let pass = 0, fail = 0
const ok = (c, m) => { if (c) { pass++; console.log("  ok  -", m) } else { fail++; console.log("  FAIL-", m) } }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
function freePort() { return new Promise((res) => { const s = http.createServer(); s.listen(0, () => { const p = s.address().port; s.close(() => res(p)) }) }) }
async function waitFor(fn, t, what) { const s = Date.now(); while (Date.now() - s < t) { try { if (await fn()) return true } catch {} await sleep(100) } throw new Error(`timeout: ${what}`) }

// ── deterministic binary payloads (hostile to naive UTF-8 round-trips) ────
const PDF_BINARY = Buffer.concat([
  Buffer.from("%PDF-1.4\n"),
  Buffer.from([0x00, 0xff, 0x80, 0x81, 0xfe, 0xc3, 0x28]), // invalid UTF-8 run
  crypto.randomBytes(0), // (determinism: no randomness below)
  Buffer.alloc(4096, 0xa5),
  Buffer.from("trailer\n%%EOF\n"),
])
const ZIP_BINARY = Buffer.concat([
  Buffer.from([0x50, 0x4b, 0x03, 0x04]), // PK..
  Buffer.from([0x00, 0x01, 0xff, 0xfe, 0xfd]),
  Buffer.alloc(8192, 0x1f),
  Buffer.from([0x50, 0x4b, 0x05, 0x06]),
])
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex")

// ── mock upstream that records what the proxy actually delivered ──────────
const seen = { put: null, form: null, formCt: null, json: null, jsonHeaders: null }
const mock = http.createServer((req, res) => {
  const chunks = []
  req.on("data", (c) => chunks.push(c))
  req.on("end", async () => {
    const raw = Buffer.concat(chunks)
    if (req.method === "PUT" && req.url === "/put") {
      seen.put = { raw, headers: req.headers }
      res.writeHead(200, { "Content-Type": "application/json" }); res.end('{"ok":true}')
    } else if (req.method === "POST" && req.url === "/form") {
      seen.formCt = req.headers["content-type"] || ""
      try {
        const fd = await new Request("http://mock/form", {
          method: "POST",
          headers: { "content-type": seen.formCt },
          body: raw,
        }).formData()
        const entries = []
        for (const [name, value] of fd.entries()) {
          if (typeof value === "string") entries.push({ name, value })
          else entries.push({ name, fileName: value.name, type: value.type, bytes: Buffer.from(await value.arrayBuffer()) })
        }
        seen.form = entries
      } catch (err) {
        seen.form = { parseError: String(err) }
      }
      res.writeHead(200, { "Content-Type": "application/json" }); res.end('{"task_id":"t-1"}')
    } else if (req.method === "GET" && req.url === "/binary") {
      res.writeHead(200, { "Content-Type": "application/octet-stream" }); res.end(ZIP_BINARY)
    } else if (req.method === "POST" && req.url === "/json") {
      seen.json = raw.toString("utf-8"); seen.jsonHeaders = req.headers
      res.writeHead(200, { "Content-Type": "application/json" }); res.end(JSON.stringify({ echoed: true }))
    } else {
      res.writeHead(404); res.end()
    }
  })
})
const mockPort = await freePort()
await new Promise((r) => mock.listen(mockPort, r))

// ── boot the server under test ─────────────────────────────────────────────
const port = await freePort()
const clipPort = await freePort()
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "llmwiki-proxybin-"))
const child = spawn(process.execPath, [SERVER_ENTRY], {
  cwd: REPO,
  env: { ...process.env, LLM_WIKI_PORT: String(port), LLM_WIKI_NO_SHARE: "1", LLM_WIKI_DATA_DIR: dataDir, LLM_WIKI_CLIP_PORT: String(clipPort) },
  stdio: ["ignore", "pipe", "pipe"],
})
let serverLog = ""
child.stdout.on("data", (d) => (serverLog += d)); child.stderr.on("data", (d) => (serverLog += d))

async function req(p, method, body) {
  const res = await fetch(`http://127.0.0.1:${port}/api/proxy`, { method, headers: { "Content-Type": "application/json" }, body })
  const text = await res.text()
  let json = null
  try { json = JSON.parse(text) } catch {}
  return { status: res.status, text, json, buffer: Buffer.from(text, "binary") }
}

try {
  await waitFor(async () => (await fetch(`http://127.0.0.1:${port}/api/health`)).ok, 8000, "server health")
  console.log(`server (${SERVER_ENTRY}) up on ${port}, mock upstream on ${mockPort}`)

  // 1. binary PUT via bodyBase64 — byte-exact delivery
  {
    const r = await req(port, "POST", JSON.stringify({
      url: `http://127.0.0.1:${mockPort}/put`,
      method: "PUT",
      headers: { "X-Test": "kept", "Connection": "dropped" },
      bodyBase64: PDF_BINARY.toString("base64"),
    }))
    ok(r.status === 200 && r.json?.ok === true, `bodyBase64 PUT proxied (HTTP ${r.status})`)
    ok(seen.put !== null && seen.put.raw.equals(PDF_BINARY), `upstream received BYTE-EXACT body (${seen.put?.raw.length ?? 0}/${PDF_BINARY.length} bytes, sha ${sha(seen.put?.raw ?? Buffer.alloc(0)).slice(0, 12)}… vs ${sha(PDF_BINARY).slice(0, 12)}…)`)
    ok(seen.put?.headers["x-test"] === "kept", "custom header forwarded with binary body")
    ok(seen.put?.headers["connection"] !== "dropped", "caller's hop-by-hop header value not forwarded (transport may add its own)")
  }

  // 2. formEntries → real multipart upload on the server side
  {
    const r = await req(port, "POST", JSON.stringify({
      url: `http://127.0.0.1:${mockPort}/form`,
      method: "POST",
      headers: { "Content-Type": "multipart/form-data; boundary=STALE-BROWSER-BOUNDARY" },
      formEntries: [
        { name: "backend", value: "hybrid-engine" },
        { name: "return_md", value: "true" },
        { name: "files", fileName: "sample.pdf", contentType: "application/pdf", base64: PDF_BINARY.toString("base64") },
      ],
    }))
    ok(r.status === 200 && r.json?.task_id === "t-1", `formEntries POST proxied (HTTP ${r.status})`)
    ok(/^multipart\/form-data; boundary=/.test(seen.formCt ?? ""), `server generated its OWN multipart boundary (got "${seen.formCt}")`)
    ok(!(seen.formCt ?? "").includes("STALE-BROWSER-BOUNDARY"), "stale browser boundary dropped")
    if (Array.isArray(seen.form)) {
      const text = Object.fromEntries(seen.form.filter((e) => "value" in e).map((e) => [e.name, e.value]))
      const file = seen.form.find((e) => e.name === "files")
      ok(text.backend === "hybrid-engine" && text.return_md === "true", "text form fields delivered")
      ok(file && file.fileName === "sample.pdf" && file.type === "application/pdf", `file part metadata delivered (name=${file?.fileName}, type=${file?.type})`)
      ok(Boolean(file) && file.bytes.equals(PDF_BINARY), `file part BYTE-EXACT (${file?.bytes.length ?? 0}/${PDF_BINARY.length} bytes)`)
    } else {
      ok(false, `multipart parsed by upstream (got ${JSON.stringify(seen.form)})`)
      ok(false, "text form fields delivered"); ok(false, "file part metadata delivered"); ok(false, "file part BYTE-EXACT")
    }
  }

  // 3. binary response streamed back byte-exact
  {
    const res = await fetch(`http://127.0.0.1:${port}/api/proxy`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ url: `http://127.0.0.1:${mockPort}/binary`, method: "GET" }),
    })
    const got = Buffer.from(await res.arrayBuffer())
    ok(res.status === 200, `binary GET proxied (HTTP ${res.status})`)
    ok(got.equals(ZIP_BINARY), `binary response BYTE-EXACT (${got.length}/${ZIP_BINARY.length} bytes)`)
    ok((res.headers.get("content-type") || "").includes("application/octet-stream"), "upstream content-type preserved on binary response")
  }

  // 4. pre-existing text-body contract unchanged
  {
    const payload = { model: "m", messages: [{ role: "user", content: "héllo 中文" }] }
    const r = await req(port, "POST", JSON.stringify({
      url: `http://127.0.0.1:${mockPort}/json`,
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: "Bearer t" },
      body: JSON.stringify(payload),
    }))
    ok(r.status === 200 && r.json?.echoed === true, `string body POST proxied (HTTP ${r.status})`)
    ok(seen.json === JSON.stringify(payload), "JSON text body delivered byte-for-byte")
    ok(seen.jsonHeaders?.authorization === "Bearer t" && (seen.jsonHeaders?.["content-type"] || "").includes("application/json"), "headers kept for text body")
  }

  // 5. bodyContentType only fills in a missing Content-Type
  {
    await req(port, "POST", JSON.stringify({
      url: `http://127.0.0.1:${mockPort}/put`, method: "PUT",
      bodyBase64: Buffer.from([1, 2, 3]).toString("base64"),
      bodyContentType: "application/pdf",
    }))
    ok(seen.put?.headers["content-type"] === "application/pdf", "bodyContentType applied when caller sent none")
    await req(port, "POST", JSON.stringify({
      url: `http://127.0.0.1:${mockPort}/put`, method: "PUT",
      headers: { "Content-Type": "application/octet-stream" },
      bodyBase64: Buffer.from([1, 2, 3]).toString("base64"),
      bodyContentType: "application/pdf",
    }))
    ok(seen.put?.headers["content-type"] === "application/octet-stream", "explicit caller Content-Type wins over bodyContentType")
  }

  // 6. error semantics
  {
    const amb = await req(port, "POST", JSON.stringify({ url: `http://127.0.0.1:${mockPort}/put`, method: "PUT", body: "x", bodyBase64: "eA==" }))
    ok(amb.status === 400 && amb.json?.error === "Ambiguous body: send exactly one of body, bodyBase64, formEntries", "ambiguous body rejected 400")
    const nourl = await req(port, "POST", JSON.stringify({ method: "GET" }))
    ok(nourl.status === 400 && nourl.json?.error === "Missing url", "missing url rejected 400")
    const badurl = await req(port, "POST", JSON.stringify({ url: "::not a url::" }))
    ok(badurl.status === 400 && badurl.json?.error === "Invalid url", "invalid url rejected 400")
    const scheme = await req(port, "POST", JSON.stringify({ url: "file:///etc/passwd" }))
    ok(scheme.status === 400 && scheme.json?.error === "Only http(s) URLs may be proxied", "non-http scheme rejected 400")
    const badform = await req(port, "POST", JSON.stringify({ url: `http://127.0.0.1:${mockPort}/form`, method: "POST", formEntries: "nope" }))
    ok(badform.status === 400 && badform.json?.error === "formEntries must be an array", "non-array formEntries rejected 400")
  }
} finally {
  child.kill("SIGKILL")
  mock.close()
  fs.rmSync(dataDir, { recursive: true, force: true })
}

console.log(`\n${pass} passed, ${fail} failed (entry: ${SERVER_ENTRY})`)
if (fail > 0) { console.log("\n--- server log tail ---"); console.log(serverLog.slice(-2000)); process.exit(1) }
